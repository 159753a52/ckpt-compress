"""Summarize run_residual_sweep_small.py JSONs into a markdown report.

Usage: python summarize_residual_sweep_small.py <results_dir> [--out summary.md]
Every number is read from the ``<regime>_seed<seed>.json`` files in the directory.
"""
from __future__ import annotations

import argparse
import json
import statistics
from pathlib import Path

ORDER = ["excp_style", "inshrinkerator_style", "first_order", "hvp_global", "dacp",
         "probe_sample_m1", "probe_topk_m1", "probe_headtail_m2", "probe_topk_m4",
         "first_order_ucb", "iterative_first_order"]
CHALLENGERS = ["dacp", "probe_sample_m1", "probe_topk_m1", "probe_headtail_m2", "probe_topk_m4",
               "iterative_first_order", "first_order_ucb"]
BASELINES = ["excp_style", "inshrinkerator_style"]
REGIME_TITLES = {"R1": "R1: step-1000 checkpoint, reference = base weights",
                 "R2": "R2: step-3000 checkpoint, reference = base weights",
                 "R3": "R3: step-3000 checkpoint, reference = step-1000 checkpoint (inter-checkpoint)"}


MODEL_TITLES = {"pythia-410m": "Pythia-410M", "pythia-160m": "Pythia-160M", "gpt2": "GPT-2 (124M)"}
def delta(rec: dict, tag: str, sp: str) -> float:
    return (rec["evals"][tag][sp]["val"] - rec["uncompressed"]["val"]) * 1e3


def fmt(values: list[float]) -> str:
    m = statistics.mean(values)
    return f"{m:.1f}" if len(values) < 2 else f"{m:.1f} ± {statistics.stdev(values):.1f}"


def regime_section(regime: str, recs: list[dict]) -> list[str]:
    r0 = recs[0]
    sps = [str(s) for s in r0["sparsities"]]
    seeds = [r["seed"] for r in recs]
    tags = [t for t in ORDER if all(t in r["evals"] for r in recs)]
    res = r0["residual"]
    lines = [f"## {REGIME_TITLES.get(regime, regime)}", ""]
    lines.append(r0["regime_description"] + ".")
    lines.append("")
    lines.append(
        f"Seeds {seeds}. Eligible coords {res['eligible_coords']:,}, residual L2 {res['residual_l2']:.4f}, "
        f"zero-residual fraction {res['zero_residual_fraction']:.2e}. Uncompressed eval loss "
        f"{r0['uncompressed']['val']:.5f} (PPL {r0['uncompressed']['ppl']:.4f}); full restoration of all "
        f"eligible coords to the reference: loss {r0['full_restore']['val']:.5f} (PPL {r0['full_restore']['ppl']:.4f}, "
        f"Δ {(r0['full_restore']['val'] - r0['uncompressed']['val']) * 1e3:.1f}e-3)."
    )
    lines.append("")
    lines.append("Δ eval loss vs uncompressed (1e-3 nats), mean ± std over seeds; bold = lowest mean per sparsity.")
    lines.append("")
    lines.append("| method | " + " | ".join(sps) + " |")
    lines.append("|---" * (len(sps) + 1) + "|")
    means = {t: {sp: statistics.mean(delta(r, t, sp) for r in recs) for sp in sps} for t in tags}
    best = {sp: min(means[t][sp] for t in tags) for sp in sps}
    for t in tags:
        cells = []
        for sp in sps:
            c = fmt([delta(r, t, sp) for r in recs])
            cells.append(f"**{c}**" if means[t][sp] == best[sp] else c)
        lines.append(f"| {t} | " + " | ".join(cells) + " |")
    lines.append("")
    lines.append("Paired wins/ties/losses over seeds (lower Δ wins; same eval batches, per-seed scoring batches).")
    lines.append("")
    lines.append("| challenger vs baseline | " + " | ".join(sps) + " |")
    lines.append("|---" * (len(sps) + 1) + "|")
    for c in [t for t in CHALLENGERS if t in tags]:
        for b in [t for t in BASELINES if t in tags]:
            cells = []
            for sp in sps:
                w = sum(delta(r, c, sp) < delta(r, b, sp) for r in recs)
                l = sum(delta(r, c, sp) > delta(r, b, sp) for r in recs)
                cells.append(f"{w}/{len(recs) - w - l}/{l}")
            lines.append(f"| {c} vs {b} | " + " | ".join(cells) + " |")
    lines.append("")
    return lines


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("results", type=Path)
    ap.add_argument("--out", type=Path)
    args = ap.parse_args()
    by_regime: dict[str, list[dict]] = {}
    for p in sorted(args.results.glob("*_seed*.json")):
        if p.name.startswith("abl-"):
            continue
        rec = json.loads(p.read_text())
        by_regime.setdefault(rec["regime"], []).append(rec)
    models = sorted({r.get("model", "pythia-410m") for rs in by_regime.values() for r in rs}) or ["pythia-410m"]
    lines = [f"# {', '.join(MODEL_TITLES.get(m, m) for m in models)} immediate-restoration residual sweep", "",
             "Generated by `experiments/scripts/summarize_residual_sweep_small.py` from the JSON files in this "
             "directory (`experiments/scripts/run_residual_sweep_small.py`). No recovery training: the lowest-scored "
             "fraction p of eligible residual coordinates is restored to the reference and the model is evaluated on "
             "the runner's 100 held-out Alpaca eval batches (token-weighted loss). Exact global k-smallest masks except "
             "dacp (Weibull allocation, max_layer_ratio 0.999). Scoring: 8 Alpaca batches (2 x 128) per seed. "
             "Style baselines are matched-protocol scoring rules, not reproductions of ExCP or Inshrinkerator.", ""]
    for regime in sorted(by_regime):
        lines += regime_section(regime, sorted(by_regime[regime], key=lambda r: r["seed"]))
    text = "\n".join(lines)
    if args.out:
        args.out.write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
