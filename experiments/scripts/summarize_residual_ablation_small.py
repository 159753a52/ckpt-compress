"""Summarize run_residual_ablation_small.py JSONs (abl-<task>_<regime>_seed<seed>.json).

Usage: python summarize_residual_ablation_small.py <results_dir> [--out summary_ablation.md]
Reference rows (excp_style, first_order, first_order_ucb, iterative_first_order, dacp) are
read from the sweep files <regime>_seed<seed>.json of the same directory when present.
Every number is read from JSON.
"""
from __future__ import annotations

import argparse
import json
import statistics
from pathlib import Path

REF_TAGS = ["excp_style", "dacp", "first_order", "first_order_ucb", "iterative_first_order"]


def delta(rec: dict, tag: str, sp: str) -> float:
    return (rec["evals"][tag][sp]["val"] - rec["uncompressed"]["val"]) * 1e3


def fmt(values: list[float]) -> str:
    m = statistics.mean(values)
    return f"{m:.1f}" if len(values) < 2 else f"{m:.1f} ± {statistics.stdev(values):.1f}"


def table(rows: list[tuple[str, list[dict], str]], sps: list[str], extra=None) -> list[str]:
    """rows: (label, records, tag). Bold = lowest mean per column."""
    head = "| method | seeds | " + " | ".join(sps) + " |" + (f" {extra[0]} |" if extra else "")
    lines = [head, "|---" * (len(sps) + 2 + (1 if extra else 0)) + "|"]
    means = {}
    for label, recs, tag in rows:
        means[label] = {sp: statistics.mean(delta(r, tag, sp) for r in recs)
                        for sp in sps if recs and all(sp in r["evals"].get(tag, {}) for r in recs)}
    best = {sp: min((m[sp] for m in means.values() if sp in m), default=None) for sp in sps}
    for label, recs, tag in rows:
        cells = []
        for sp in sps:
            if sp not in means[label]:
                cells.append("-")
                continue
            c = fmt([delta(r, tag, sp) for r in recs])
            cells.append(f"**{c}**" if means[label][sp] == best[sp] else c)
        tail = f" {extra[1](recs, tag)} |" if extra else ""
        lines.append(f"| {label} | {len(recs)} | " + " | ".join(cells) + " |" + tail)
    return lines


def wins(recs_a, tag_a, recs_b, tag_b, sps) -> list[str]:
    by_b = {r["seed"]: r for r in recs_b}
    cells = []
    for sp in sps:
        pairs = [(delta(a, tag_a, sp), delta(by_b[a["seed"]], tag_b, sp)) for a in recs_a
                 if a["seed"] in by_b and sp in by_b[a["seed"]]["evals"].get(tag_b, {})]
        w = sum(x < y for x, y in pairs)
        l = sum(x > y for x, y in pairs)
        cells.append(f"{w}/{len(pairs) - w - l}/{l}" if pairs else "-")
    return cells


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("results", type=Path)
    ap.add_argument("--out", type=Path)
    args = ap.parse_args()
    abl: dict[tuple[str, str], list[dict]] = {}
    for p in sorted(args.results.glob("abl-*_R*_seed*.json")):
        rec = json.loads(p.read_text(encoding="utf-8"))
        abl.setdefault((rec["task"], rec["regime"]), []).append(rec)
    sweep: dict[str, list[dict]] = {}
    for p in sorted(args.results.glob("R*_seed*.json")):
        rec = json.loads(p.read_text(encoding="utf-8"))
        sweep.setdefault(rec["regime"], []).append(rec)
    regimes = sorted({r for _, r in abl})
    L = ["# Pythia-410M iterative residual pruning: ablations", "",
         "Generated by `experiments/scripts/summarize_residual_ablation_small.py` from the `abl-*.json` files "
         "(`experiments/scripts/run_residual_ablation_small.py`) and, for reference rows, the sweep files "
         "`R*_seed*.json` in this directory. Immediate restoration (no training), exact global k-smallest "
         "masks, 100 held-out Alpaca eval batches; entries are Δ eval loss vs the uncompressed checkpoint in "
         "1e-3 nats, mean ± std over seeds (bold = lowest mean in the column). Scoring batches 2 x 128; "
         "B = 8 unless stated. A gradient pass = one backward per scoring batch at the current point.", "",
         "Iterative schedules. *list*: stages 0.5, 0.8, 0.9, 0.95, 0.98, 0.99, 0.995 (the sweep's "
         "iterative_first_order; reaching sparsity P uses the stages up to P). *geometric K*: for target P, "
         "P_j = 1 − (1 − P)^(j/K), j = 1..K, i.e. the kept fraction shrinks by the constant factor "
         "(1 − P)^(1/K) per stage; each target is a separate run and K = 1 is one-shot |g d| with the "
         "averaged full gradient. Pruned sets are monotone across stages.", ""]
    for regime in regimes:
        ref = sorted(sweep.get(regime, []), key=lambda r: r["seed"])
        L += [f"## {regime}", ""]
        some = next(iter(v for (t, r), v in abl.items() if r == regime))[0]
        L += [some["regime_description"] + f". Uncompressed eval loss {some['uncompressed']['val']:.5f}.", ""]
        # task 2
        combo = sorted(abl.get(("combo", regime), []), key=lambda r: r["seed"])
        if combo:
            sps = [str(s) for s in combo[0]["sparsities"]]
            L += ["### Combined iterative scorers (list schedule)", ""]
            rows = [(f"{t} (sweep)", ref, t) for t in REF_TAGS if ref and t in ref[0]["evals"]]
            tags = [t for t in combo[0]["evals"] if not t.endswith("_K8")]
            rows += [(t, combo, t) for t in tags]
            L += table(rows, sps) + [""]
            k8 = [t for t in combo[0]["evals"] if t.endswith("_K8")]
            if k8:
                sps8 = [str(s) for s in combo[0]["iterative_stages"][k8[0]]]
                L += ["Same scorers on the geometric K = 8 schedule (8 stages per target):", ""]
                sched = sorted(abl.get(("sched", regime), []), key=lambda r: r["seed"])
                rows = ([("iterative_K8 (first order)", sched, "iterative_K8")] if sched else []) + \
                       [(t, combo, t) for t in k8]
                L += table(rows, sps8) + [""]
            L += ["Paired wins/ties/losses over seeds (per sparsity):", "",
                  "| challenger vs baseline | " + " | ".join(sps) + " |", "|---" * (len(sps) + 1) + "|"]
            for c in tags:
                if c == "iterative_first_order":
                    continue
                L.append(f"| {c} vs iterative_first_order | " +
                         " | ".join(wins(combo, c, combo, "iterative_first_order", sps)) + " |")
            if ref:
                for c in tags:
                    L.append(f"| {c} vs first_order_ucb (sweep) | " +
                             " | ".join(wins(combo, c, ref, "first_order_ucb", sps)) + " |")
            L.append("")
            by_seed = {r["seed"]: r for r in ref}
            diffs = [abs(delta(c, "iterative_first_order", sp) - delta(by_seed[c["seed"]], "iterative_first_order", sp))
                     for c in combo if c["seed"] in by_seed and "iterative_first_order" in c["evals"]
                     and "iterative_first_order" in by_seed[c["seed"]]["evals"] for sp in sps]
            if diffs:
                L += [f"Re-run check: iterative_first_order here vs the sweep file of the same seed differs by at most "
                      f"{max(diffs):.1f}e-3 nats over {len(diffs)} (seed, sparsity) cells (identical batches and scoring "
                      "code, so nonzero differences reflect run-to-run GPU numerics).", ""]
            timing = combo[0].get("timing", {})
            if timing:
                L += ["Wall time of one list-schedule run (7 stages incl. 7 evaluations, seed "
                      f"{combo[0]['seed']}, GPU): " +
                      ", ".join(f"{t} {v['total_s']:.0f} s" for t, v in timing.items()) + ".", ""]
        # task 1
        sched = sorted(abl.get(("sched", regime), []), key=lambda r: r["seed"])
        if sched:
            sps = [str(s) for s in sched[0]["sparsities"]]
            L += ["### Schedule ablation (geometric K, first-order score)", ""]
            rows = [(t, sched, t) for t in sorted(sched[0]["evals"], key=lambda t: int(t.split("_K")[1]))]
            if combo:
                rows.append(("list schedule (iterative_first_order)", combo, "iterative_first_order"))
            L += table(rows, sps) + [""]
            passes = {sp: sum(1 for p in [0.5, 0.8, 0.9, 0.95, 0.98, 0.99, 0.995] if p <= float(sp) + 1e-12)
                      for sp in sps}
            L += ["Gradient passes: iterative_K{K} uses K at every target; the list schedule uses " +
                  ", ".join(f"{passes[sp]} at {sp}" for sp in sps) + ".", ""]
        # task 3
        bt = sorted(abl.get(("batches", regime), []), key=lambda r: r["seed"])
        if bt:
            sps = [str(s) for s in bt[0]["sparsities"]]
            L += ["### Number of scoring batches B", "",
                  "Scoring set = first B of the seed's 16 training-pool batches "
                  "(`partition_repeated_seed_batches(pool, 100, 1, 16, seed)`; its first 8 are the sweep's "
                  "scoring batches; the pool is disjoint from the evaluation batches).", ""]
            fams = ["first_order", "first_order_ucb", "iterative_first_order"]
            rows = [(f"{f}_B{B}", bt, f"{f}_B{B}") for f in fams for B in (2, 4, 8, 16)
                    if f"{f}_B{B}" in bt[0]["evals"]]
            L += table(rows, sps) + [""]
        # best-settings combination
        best = sorted(abl.get(("best", regime), []), key=lambda r: r["seed"])
        if best:
            sps = [str(s) for s in best[0]["sparsities"]]
            L += ["### Best-settings combination (geometric K = 16)", ""]
            rows = [(f"{t} (sweep)", ref, t) for t in ("first_order", "first_order_ucb", "iterative_first_order")
                    if ref and t in ref[0]["evals"]]
            if sched:
                rows.append(("iterative_K16 (B = 8)", sched, "iterative_K16"))
            if combo and "iterative_ucb_K8" in combo[0]["evals"]:
                rows.append(("iterative_ucb_K8 (B = 8)", combo, "iterative_ucb_K8"))
            rows += [(t, best, t) for t in best[0]["evals"]]
            L += table(rows, sps) + [""]
    text = "\n".join(L)
    if args.out:
        args.out.write_text(text + "\n", encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
